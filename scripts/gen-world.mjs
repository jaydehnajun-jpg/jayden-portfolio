// Generates src/worldMap.js: an abstracted world map (land sampled as a grid of dots, Americas on the left) plus the
// pixel position of each place.
// Run:  npm i --no-save d3-geo topojson-client world-atlas && node scripts/gen-world.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoNaturalEarth1, geoPath, geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const W = 960, SPACING = 8, CENTER = 10;                    // centred on 10°E: the Americas sit on the left, Asia on the right
const PLACES = [                               // [lon, lat]
  ['portland', -122.68, 45.52], ['seoul', 126.98, 37.57], ['la', -118.24, 34.05], ['london', -0.13, 51.51], ['seattle', -122.33, 47.61],
];
const proj = geoNaturalEarth1().rotate([-CENTER, 0]).fitWidth(W, { type: 'Sphere' });
const H = Math.ceil(geoPath(proj).bounds({ type: 'Sphere' })[1][1]);
const f1 = (n) => Math.round(n * 10) / 10;

let dots = '';
for (let y = SPACING / 2; y < H; y += SPACING) {
  const off = (Math.round(y / SPACING) % 2) * (SPACING / 2);                // staggered rows
  for (let x = SPACING / 2 + off; x < W; x += SPACING) {
    const p = proj.invert([x, y]);
    if (p && geoContains(land, p)) dots += `M${f1(x)} ${f1(y)}h0`;
  }
}
const pts = Object.fromEntries(PLACES.map(([k, lon, lat]) => { const [x, y] = proj([lon, lat]); return [k, [f1(x), f1(y)]]; }));

writeFileSync(new URL('../src/worldMap.js', import.meta.url),
  `// Generated by scripts/gen-world.mjs: do not edit by hand.\nexport const MAP = ${JSON.stringify({ W, H, dots, pts })};\n`);
console.log({ W, H, bytes: dots.length, pts });
