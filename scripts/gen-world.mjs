// Generates src/worldMap.js: an abstracted world map (land as a few coarse, paper-cut shapes, Americas on the left) plus the
// pixel position of each place and the box that frames the land (no Antarctica).
// Run:  npm i --no-save d3-geo topojson-client world-atlas && node scripts/gen-world.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const W = 960, CENTER = 10, EPS = 2.4, MIN_AREA = 30;   // centred on 10°E: the Americas sit on the left, Asia on the right
const PLACES = [                                         // [lon, lat]
  ['portland', -122.68, 45.52], ['seoul', 126.98, 37.57], ['la', -118.24, 34.05], ['london', -0.13, 51.51], ['sf', -122.42, 37.77], ['seattle', -122.33, 47.61],
];
const proj = geoNaturalEarth1().rotate([-CENTER, 0]).fitWidth(W, { type: 'Sphere' });
const H = Math.ceil(geoPath(proj).bounds({ type: 'Sphere' })[1][1]);
const f1 = (n) => Math.round(n * 10) / 10;

// collect the projected rings
const rings = []; let cur = null;
geoPath(proj, { moveTo: (x, y) => { cur = [[x, y]]; rings.push(cur); }, lineTo: (x, y) => cur.push([x, y]), closePath() {}, arc() {}, rect() {} })(land);

// Douglas-Peucker: flatten each outline into a few straight edges
const rdp = (pts, eps) => {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    let m = -1, md = 0;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len; if (d > md) { md = d; m = i; } }
    if (md > eps) { keep[m] = 1; stack.push([a, m], [m, b]); }
  }
  return pts.filter((_, i) => keep[i]);
};
// an outline starts and ends at (nearly) the same point, so split it at the farthest point first
const simplify = (ring, eps) => {
  let m = 0, md = 0;
  for (let i = 1; i < ring.length; i++) { const d = Math.hypot(ring[i][0] - ring[0][0], ring[i][1] - ring[0][1]); if (d > md) { md = d; m = i; } }
  return [...rdp(ring.slice(0, m + 1), eps), ...rdp(ring.slice(m), eps).slice(1)];
};
const area = (p) => Math.abs(p.reduce((s, [x, y], i) => { const [x2, y2] = p[(i + 1) % p.length]; return s + (x * y2 - x2 * y); }, 0) / 2);

let d = '', top = H, bottom = 0;
for (const r of rings) {
  const ys = r.map((p) => p[1]);
  if (Math.min(...ys) > H * 0.8) continue;                     // Antarctica
  const s = simplify(r, EPS);
  if (s.length < 3 || area(s) < MIN_AREA) continue;
  top = Math.min(top, ...s.map((p) => p[1])); bottom = Math.max(bottom, ...s.map((p) => p[1]));
  d += 'M' + s.map(([x, y]) => f1(x) + ' ' + f1(y)).join('L') + 'Z';
}
const pts = Object.fromEntries(PLACES.map(([k, lon, lat]) => { const [x, y] = proj([lon, lat]); return [k, [f1(x), f1(y)]]; }));
const y0 = Math.max(0, Math.floor(top) - 8), y1 = Math.ceil(bottom) + 8;

writeFileSync(new URL('../src/worldMap.js', import.meta.url),
  `// Generated by scripts/gen-world.mjs: do not edit by hand.\nexport const MAP = ${JSON.stringify({ W, y0, h: y1 - y0, land: d, pts })};\n`);
console.log({ W, y0, h: y1 - y0, bytes: d.length, pts });
